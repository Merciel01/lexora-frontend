import { test, expect } from "@playwright/test";

test("modèle CPU réel et abstention du corpus en révision", async ({ page }) => {
  test.skip(process.env.LEXORA_TEST_LOCAL_LLM !== "1", "Modèle local requis pour cette recette explicite.");
  test.setTimeout(180000);
  const errors: string[] = [];
  page.on("pageerror", error => errors.push(error.message));
  const email = `local-model-${Date.now()}@lexora.test`;
  const password = "LocalRecipe!928461";
  await page.goto("/register");
  await page.getByLabel("Nom complet").fill("Recette modèle local");
  await page.getByLabel("Adresse e-mail").fill(email);
  await page.getByLabel("Mot de passe", { exact: true }).fill(password);
  await page.getByLabel("Confirmer le mot de passe").fill(password);
  await page.getByRole("button", { name: "Créer mon compte" }).click();
  await expect(page.getByText("Compte créé. Vous pouvez maintenant vous connecter à LEXORA.")).toBeVisible();
  await page.goto("/login");
  await page.getByLabel("Adresse e-mail").fill(email);
  await page.getByLabel("Mot de passe", { exact: true }).fill(password);
  await page.getByRole("button", {name:"Se connecter",exact:true}).click();
  await expect(page).toHaveURL(/\/app$/);
  await page.getByRole("link", {name:"Modèle local",exact:true}).click();
  await page.getByLabel("Votre question").fill("Réponds en une seule phrase : comment préparer une prise de parole claire ?");
  const responsePromise=page.waitForResponse(r=>r.url().endsWith('/api/ai/local') && r.request().method()==='POST', {timeout:150000});
  await page.getByRole("button", {name:"Envoyer",exact:true}).click();
  await expect(page.getByRole("status")).toBeVisible();
  const response=await responsePromise;
  expect(response.status(),await response.text()).toBe(200);
  const answer=await response.json();
  expect(answer.model).toBe('Qwen3-4B-Q4_K_M');
  expect(answer.text.length).toBeGreaterThan(20);
  expect(answer.seconds).toBeGreaterThan(0);
  await expect(page.getByRole('heading',{name:'Réponse',exact:true})).toBeVisible();
  await expect(page.getByText(answer.text,{exact:true})).toBeVisible();
  await page.screenshot({path:'test-results/local-model-real.png',fullPage:true});
  await page.getByLabel('Mode',{exact:true}).selectOption('rag');
  const abstention=page.waitForResponse(r=>r.url().endsWith('/api/ai/local') && r.request().method()==='POST');
  await page.getByRole('button',{name:'Envoyer',exact:true}).click();
  expect((await (await abstention).json()).status).toBe('no_validated_source');
  await expect(page.getByText('Aucune réponse juridique générée : le corpus est encore en révision.',{exact:true})).toBeVisible();
  expect(errors).toEqual([]);
});
